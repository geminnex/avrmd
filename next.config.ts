import type { NextConfig } from "next";

/**
 * Sent on every response. The CSP allows nothing from other origins: every
 * script, style, image and request on AVRMD is first-party (uploads are
 * served from /media). 'unsafe-inline' stays for scripts because Next's
 * hydration data is inline; it can tighten to nonces later. Dev mode needs
 * eval for fast refresh, so the CSP applies to production builds only.
 */
const contentSecurityPolicy = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const securityHeaders = [
  { key: "Strict-Transport-Security", value: "max-age=31536000; includeSubDomains" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  ...(process.env.NODE_ENV === "production"
    ? [{ key: "Content-Security-Policy", value: contentSecurityPolicy }]
    : []),
];

const nextConfig: NextConfig = {
  output: "standalone",
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  async redirects() {
    return [
      // /advertise was published before promotion merged into the wider
      // organisation journey.
      { source: "/advertise", destination: "/for-organizations", permanent: true },
    ];
  },
};

export default nextConfig;
